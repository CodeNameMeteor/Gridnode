"""Rust bindings for the mod API: sdk/include/gridnode/api.h -> bindings/rust/gridnode/src/sys.rs.

api.h is GridNode's own header and is written in a small, regular subset of C (fixed-width types,
typedef'd structs and function pointers, one gn_api table), so a purpose-built parser is enough and
the bindings cannot drift from the header: CI regenerates them and fails on any difference.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass

PRIMS = {
    "void": "()", "int": "c_int", "unsigned": "u32", "float": "f32", "double": "f64", "char": "c_char",
    "size_t": "usize", "uint8_t": "u8", "uint16_t": "u16", "uint32_t": "u32", "uint64_t": "u64",
    "int8_t": "i8", "int16_t": "i16", "int32_t": "i32", "int64_t": "i64",
}


@dataclass
class Param:
    ctype: str
    name: str
    array: int | None = None


def _strip(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    # Conditional blocks: keep the first branch only (gn_transform's alignment spellings).
    out, skip, depth = [], [], 0
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("#if"):
            depth += 1
            skip.append(False)
            continue
        if s.startswith("#elif") or s.startswith("#else"):
            if skip:
                skip[-1] = True
            continue
        if s.startswith("#endif"):
            if skip:
                skip.pop()
            continue
        if any(skip) or s.startswith("#"):
            continue
        out.append(line)
    return "\n".join(out)


def _rust_type(ctype: str, structs: set[str], fnptrs: set[str]) -> str:
    t = ctype.replace("alignas(16)", "").strip()
    const = False
    stars = t.count("*")
    t = t.replace("*", " ").strip()
    words = t.split()
    if words and words[0] == "const":
        const = True
        words = words[1:]
    base = " ".join(w for w in words if w != "const")
    if base in PRIMS:
        r = PRIMS[base]
    elif base in structs or base == "gn_type":
        r = base
    elif base in fnptrs:
        r = base
    else:
        raise ValueError(f"api.h: unknown type {ctype!r}")
    if stars == 0:
        return r
    if r == "()":
        r = "c_void"
    ptr = "*const " if const else "*mut "
    out = ptr + r
    for _ in range(stars - 1):
        out = "*mut " + out
    return out


def _params(text: str) -> list[Param]:
    text = text.strip()
    if text in ("", "void"):
        return []
    out = []
    for i, p in enumerate(x.strip() for x in text.split(",")):
        m = re.match(r"(.*?)([A-Za-z_]\w*)\s*(\[(\d+)\])?$", p)
        if not m or m.group(1).strip() in ("", "const"):
            out.append(Param(p, f"a{i}"))
            continue
        ctype, name = m.group(1).strip(), m.group(2)
        out.append(Param(ctype, name, int(m.group(4)) if m.group(4) else None))
    return out


def _fn(ret: str, params: list[Param], structs, fnptrs) -> str:
    args = []
    for p in params:
        t = p.ctype + ("*" if p.array else "")  # an array parameter is a pointer
        args.append(f"{_safe(p.name)}: {_rust_type(t, structs, fnptrs)}")
    r = _rust_type(ret, structs, fnptrs)
    return f"unsafe extern \"C\" fn({', '.join(args)})" + ("" if r == "()" else f" -> {r}")


def _safe(name: str) -> str:
    return name + "_" if name in ("type", "fn", "loop", "move", "ref", "self", "use", "mod", "in", "as", "match", "impl", "where", "struct", "enum", "let", "const", "static", "box", "dyn", "for", "if", "else", "while", "return", "break", "continue", "crate", "super", "trait", "pub", "mut", "true", "false", "extern", "unsafe", "async", "await", "override", "final", "macro", "priv", "typeof", "yield", "abstract", "become", "do", "virtual", "unsized") else name


def parse(header: str):
    text = _strip(header)
    defines = re.findall(r"^\s*#define\s+(GN_\w+)\s+(0x[0-9A-Fa-f]+|[0-9]+)u?\b", header, flags=re.M)
    enums = re.findall(r"enum\s+(\w+)\s*\{(.*?)\}", text, flags=re.S)
    structs_src = re.findall(r"typedef\s+struct\s+(\w+)\s*\{(.*?)\}\s*\w+\s*;", text, flags=re.S)
    fnptr_src = re.findall(r"typedef\s+([\w\s\*]+?)\s*\(\*\s*(\w+)\)\s*\((.*?)\)\s*;", text, flags=re.S)
    return defines, enums, structs_src, fnptr_src


def emit(header: str) -> str:
    defines, enums, structs_src, fnptr_src = parse(header)
    structs = {name for name, _ in structs_src}
    fnptrs = {name for _, name, _ in fnptr_src}
    o = []
    w = o.append
    w("// Generated by tools/gen/gridnode.py rust from sdk/include/gridnode/api.h. Do not edit.\n")
    w("#![allow(non_camel_case_types, non_upper_case_globals, dead_code)]\n\n")
    w("use core::ffi::{c_char, c_int, c_void};\n\n")
    for name, value in defines:
        if name in ("GN_MOD_EXPORT",):
            continue
        w(f"pub const {name}: u32 = {value};\n")
    w("\n")
    for ename, body in enums:
        value = 0
        for item in (x.strip() for x in body.split(",")):
            if not item:
                continue
            if "=" in item:
                n, v = (x.strip() for x in item.split("="))
                value = int(v, 0)
            else:
                n = item
            w(f"pub const {n}: c_int = {value};\n")
            value += 1
    w("\n/// A runtime TypeInfo / ClassInfo of the engine (opaque).\n#[repr(C)]\npub struct gn_type {\n    _private: [u8; 0],\n}\n\n")
    # Function pointer typedefs come before the structs that use them, and vice versa: Rust does
    # not care about order, so emit typedefs first.
    for ret, name, params in fnptr_src:
        if name == "gn_mod_load_fn":
            continue
        w(f"pub type {name} = Option<{_fn(ret.strip(), _params(params), structs, fnptrs)}>;\n")
    w("\n")
    for name, body in structs_src:
        aligned = "alignas(16)" in body or "aligned(16)" in body
        w(f"#[repr(C{', align(16)' if aligned else ''})]\n#[derive(Copy, Clone)]\npub struct {name} {{\n")
        for decl in (d.strip() for d in body.split(";")):
            if not decl:
                continue
            decl = decl.replace("alignas(16)", "").strip()
            fm = re.match(r"(.*?)\(\*\s*(\w+)\)\s*\((.*)\)$", decl, flags=re.S)
            if fm:  # a function pointer member (gn_api)
                ret, fname, params = fm.group(1).strip(), fm.group(2), " ".join(fm.group(3).split())
                w(f"    pub {_safe(fname)}: Option<{_fn(ret, _params(params), structs, fnptrs)}>,\n")
                continue
            m = re.match(r"(.*?)(\w+)\s*(\[(\d+)\])?$", " ".join(decl.split()))
            ctype, fname, n = m.group(1).strip(), m.group(2), m.group(4)
            rt = _rust_type(ctype, structs, fnptrs)
            w(f"    pub {_safe(fname)}: {f'[{rt}; {n}]' if n else rt},\n")
        w("}\n\n")
    w("/// The mod's entry point: `#[no_mangle] pub unsafe extern \"C\" fn gn_mod_load(api: *const gn_api) -> c_int`.\n")
    w("pub type gn_mod_load_fn = unsafe extern \"C\" fn(api: *const gn_api) -> c_int;\n")
    w(_layout_asserts(header, [n for n, _ in structs_src]))
    return "".join(o)


def _layout_asserts(header: str, structs: list[str]) -> str:
    """Compile-time size checks from the C compiler's own sizeof (when gcc is available)."""
    cc = shutil.which("gcc") or shutil.which("cc")
    if not cc:
        return ""
    src = "#include <stdio.h>\n#include <stddef.h>\n" + header + "\nint main(void){\n"
    for s in structs:
        src += f'printf("{s} %zu\\n", sizeof({s}));\n'
    src += "return 0;}\n"
    with tempfile.TemporaryDirectory() as d:
        c, exe = f"{d}/l.c", f"{d}/l"
        with open(c, "w") as f:
            f.write(src)
        if subprocess.run([cc, "-x", "c", c, "-o", exe], capture_output=True).returncode != 0:
            return ""
        out = subprocess.run([exe], capture_output=True, text=True).stdout
    lines = ["\n// Sizes from the C compiler (64-bit), checked at compile time.\n"]
    for line in out.split("\n"):
        if line.strip():
            n, size = line.split()
            lines.append(f"const _: () = assert!(core::mem::size_of::<{n}>() == {size});\n")
    return "".join(lines)
