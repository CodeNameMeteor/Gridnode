"""engine.hpp: everything in the annotations, as constants. Needs no dump, so gridnode.dll itself
can be built from it (the build check reads its fingerprint)."""

from __future__ import annotations

import io

from . import __version__
from .annotations import Database, Meta


def _comment(meta: Meta | None, extra: str = "") -> str:
    parts = []
    if extra:
        parts.append(extra)
    if meta is not None:
        if meta.confidence != "confirmed":
            parts.append(f"[{meta.confidence}]")
        if meta.note:
            note = " ".join(meta.note.split())
            parts.append(note if len(note) <= 140 else note[:137] + "...")
    return ("  // " + " ".join(parts)) if parts else ""


def _cstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(db: Database) -> str:
    o = io.StringIO()
    w = o.write
    w("#pragma once\n")
    w(f"// Generated by gridnode-gen {__version__} from db/annotations ({len(db.files)} files). Do not edit:\n")
    w("// change the annotations and regenerate. All addresses are image VAs (base 0x140000000);\n")
    w("// gn::mem::rva() converts them to the running process.\n")
    w("#include <cstddef>\n#include <cstdint>\n\nnamespace gn::engine {\n\n")

    w("// ---- Globals -------------------------------------------------------------------------------\n")
    w("namespace global {\n")
    for g in sorted(db.globals.values(), key=lambda g: g.name):
        w(f"inline constexpr uint64_t {g.name} = {g.va:#x};{_comment(g.meta, str(g.type))}\n")
    w("} // namespace global\n\n")

    w("// ---- Functions -----------------------------------------------------------------------------\n")
    w("namespace function {\n")
    for f in sorted(db.functions.values(), key=lambda f: f.name):
        w(f"inline constexpr uint64_t {f.name} = {f.va:#x};{_comment(f.meta, _sig_text(f.signature))}\n")
    w("} // namespace function\n\n")

    w("// ---- Code sites (addresses of instructions) ------------------------------------------------\n")
    w("namespace code {\n")
    for c in sorted(db.code.values(), key=lambda c: c.name):
        w(f"inline constexpr uint64_t {c.name} = {c.va:#x};{_comment(c.meta)}\n")
    w("} // namespace code\n\n")

    w("// ---- Hook points: pointers GridNode may swap (never code) ---------------------------------\n")
    w("namespace hook {\n")
    w("enum class Kind : uint8_t { VtableSlot, CreatorSlot, Pointer };\n")
    w("struct Point {\n    const char* name;\n    Kind kind;\n    uint64_t slot;     // the pointer that is swapped\n"
      "    uint64_t original; // what it holds in this build\n};\n")
    kinds = {"vtable-slot": "Kind::VtableSlot", "creator-slot": "Kind::CreatorSlot", "pointer": "Kind::Pointer"}
    for h in sorted(db.hooks.values(), key=lambda h: h.name):
        sig = _sig_text(h.signature) if h.signature else ""
        w(f"inline constexpr Point {h.name}{{{_cstr(h.name)}, {kinds[h.kind]}, {h.slot:#x}, {h.original:#x}}};"
          f"{_comment(h.meta, sig)}\n")
    w("} // namespace hook\n\n")

    w("// ---- Runtime classes: members and virtual functions reflection does not describe -----------\n")
    w("// cls::<Class>::off::<member> (byte offset), ::vf::<virtual> (vtable byte offset), ::va::<virtual>\n")
    w("// (the function in this build), ::vtable (the class's vtable).\n")
    w("namespace cls {\n")
    for c in sorted(db.classes.values(), key=lambda c: c.name):
        w(f"namespace {c.name} {{{_comment(c.meta, 'realm: ' + c.realm)}\n")
        if c.vtable is not None:
            w(f"inline constexpr uint64_t vtable = {c.vtable:#x};\n")
        if c.members:
            w("namespace off {\n")
            for m in sorted(c.members, key=lambda m: m.offset):
                w(f"inline constexpr uint32_t {m.name} = {m.offset:#x};{_comment(m.meta, str(m.type))}\n")
            w("} // namespace off\n")
        if c.virtuals:
            w("namespace vf {\n")
            for v in sorted(c.virtuals, key=lambda v: v.offset):
                w(f"inline constexpr uint32_t {v.name} = {v.offset:#x};{_comment(v.meta, _sig_text(v.signature))}\n")
            w("} // namespace vf\n")
            vas = [v for v in c.virtuals if v.va is not None]
            if vas:
                w("namespace va {\n")
                for v in sorted(vas, key=lambda v: v.offset):
                    w(f"inline constexpr uint64_t {v.name} = {v.va:#x};\n")
                w("} // namespace va\n")
        w(f"}} // namespace {c.name}\n")
    w("} // namespace cls\n\n")

    w("// ---- Structs that are not reflected: st::<Struct>::size / ::off::<member> ---------------------\n")
    w("namespace st {\n")
    for s in sorted(db.structs.values(), key=lambda s: s.name):
        w(f"namespace {s.name} {{{_comment(s.meta)}\n")
        w(f"inline constexpr uint32_t size = {s.size:#x};{'  // only the members below are known' if s.opaque else ''}\n")
        if s.members:
            w("namespace off {\n")
            for m in sorted(s.members, key=lambda m: m.offset):
                w(f"inline constexpr uint32_t {m.name} = {m.offset:#x};{_comment(m.meta, str(m.type))}\n")
            w("} // namespace off\n")
        w(f"}} // namespace {s.name}\n")
    w("} // namespace st\n\n")

    w("// ---- Member tables (for tools such as the in-game inspector) ---------------------------------\n")
    w("// meta::classMembers: members of runtime classes (cls::), meta::structMembers: of structs (st::).\n")
    w("namespace meta {\n")
    w("struct Member { const char* owner; const char* name; uint32_t offset; const char* type; const char* note; };\n")
    for table, items in (("classMembers", db.classes.values()), ("structMembers", db.structs.values())):
        w(f"inline constexpr Member {table}[] = {{\n")
        rows = 0
        for c in sorted(items, key=lambda c: c.name):
            for m in sorted(c.members, key=lambda m: m.offset):
                note = " ".join((m.meta.note or "").split()) if m.meta is not None else ""
                w(f"    {{{_cstr(c.name)}, {_cstr(m.name)}, {m.offset:#x}, {_cstr(str(m.type))}, {_cstr(note)}}},\n")
                rows += 1
        if not rows:
            w("    {nullptr, nullptr, 0, nullptr, nullptr},\n")
        w("};\n")
    w("} // namespace meta\n\n")

    w("// ---- Property / event name hashes (djb2-xor) -------------------------------------------------\n")
    w("namespace hash {\n")
    props = {}
    for c in db.classes.values():
        for pr in c.properties:
            props.setdefault(pr.name, pr)
    for name in sorted(props):
        w(f"inline constexpr uint32_t {name} = {props[name].hash:#010x};\n")
    w("} // namespace hash\n\n")

    w("// ---- Constants ------------------------------------------------------------------------------\n")
    w("namespace constant {\n")
    for c in sorted(db.constants.values(), key=lambda c: c.name):
        if isinstance(c.value, str):
            w(f"inline constexpr const char* {c.name} = {_cstr(c.value)};{_comment(c.meta)}\n")
        else:
            w(f"inline constexpr uint64_t {c.name} = {c.value:#x};{_comment(c.meta)}\n")
    w("} // namespace constant\n\n")

    w("// ---- Build fingerprint (checked by gn::build::check before anything is touched) -------------\n")
    w("namespace fingerprint {\n")
    w("struct Type { const char* name; uint64_t ti; };\n")
    w("struct Slot { const char* what; uint64_t slot; uint64_t fn; };\n")
    w("struct Code { const char* what; uint64_t at; uint32_t skip; uint32_t count; uint8_t bytes[32]; bool required; };\n")
    w("inline constexpr Type types[] = {\n")
    for t in db.fp_types:
        w(f"    {{{_cstr(t.name)}, {t.ti:#x}}},\n")
    w("};\ninline constexpr Slot slots[] = {\n")
    for s in db.fp_slots:
        w(f"    {{{_cstr(s.what)}, {s.slot:#x}, {s.fn:#x}}},\n")
    w("};\ninline constexpr Code code[] = {\n")
    for c in db.fp_code:
        b = ", ".join(f"0x{x:02X}" for x in c.data)
        w(f"    {{{_cstr(c.what)}, {c.at:#x}, {c.skip}, {len(c.data)}, {{{b}}}, {'true' if c.required else 'false'}}},\n")
    w("};\n} // namespace fingerprint\n\n")
    w("} // namespace gn::engine\n")
    return o.getvalue()


def _sig_text(sig) -> str:
    params = ", ".join(str(p.type) + (f" {p.name}" if p.name else "") for p in sig.params)
    return f"{sig.returns}({params})"
