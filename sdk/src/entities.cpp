// on_created: every entity class the engine can create has an entity creator (ClassInfo+0x50 /
// +0x58, see the dump's "creators"). The engine creates entities through the creator's vtable
// slot +8: `void* create(creator, EntityCreationInfo*, a3, a4)`, which returns the new entity or
// null. On server creators that slot is the class's factory; on client creators it is a shared
// wrapper (0x14304bf60 -> 0x143163210) that may decline (null) and otherwise reaches the class's
// factory through vtable +0x70 and +0x40. Either way +8 is the one entry point. GridNode wraps
// that slot (a pointer swap) and calls the listeners whose class the new entity is.
//
// Several creators can share one vtable, so a detour serves every class whose creator uses that
// slot and filters by the created entity's type. Detours come from a fixed pool of functions,
// one per slot, generated by a template.

#include <windows.h>

#include <algorithm>
#include <array>
#include <memory>
#include <mutex>
#include <shared_mutex>
#include <utility>
#include <vector>

#include "gridnode/log.hpp"
#include "gridnode/mem.hpp"
#include "host.hpp"

namespace gn::host {
namespace {

using FactoryFn = void* (*)(void* creator, void* ci, void* a3, void* a4);

struct Listener {
    std::string owner;
    const reflect::Type* type;
    gn_created_fn fn;
    void* user;
};

constexpr size_t kPool = 2048; // the engine has 1,092 distinct creator vtables
constexpr uint64_t kCreatorFactorySlot = 8;

struct SlotState {
    uint64_t slot = 0;
    uint64_t original = 0; // written by HookTable::install before the slot is swapped
    std::vector<Listener> listeners;
};

std::array<SlotState, kPool> g_slots;
size_t g_used = 0;
std::shared_mutex g_lock; // listeners are read on game threads, added from GridNode/mod threads

template <size_t I> void* factoryDetour(void* creator, void* ci, void* a3, void* a4) {
    SlotState& s = g_slots[I];
    void* entity = reinterpret_cast<FactoryFn>(s.original)(creator, ci, a3, a4);
    if (!entity) return entity;
    const reflect::Type* t = registry().typeOf(mem::ProcessMemory(), reinterpret_cast<uint64_t>(entity));
    if (!t) return entity;
    std::shared_lock<std::shared_mutex> lock(g_lock);
    for (const Listener& l : s.listeners)
        if (registry().isKindOf(t, l.type)) l.fn(entity, ci, l.user);
    return entity;
}

template <size_t... I> constexpr std::array<FactoryFn, sizeof...(I)> makeDetours(std::index_sequence<I...>) {
    return {&factoryDetour<I>...};
}
const std::array<FactoryFn, kPool> g_detours = makeDetours(std::make_index_sequence<kPool>{});

// The pool index for a slot, hooking it on first use. -1 on failure.
int slotIndex(uint64_t slot, std::string& why) {
    for (size_t i = 0; i < g_used; ++i)
        if (g_slots[i].slot == slot) return int(i);
    if (g_used == kPool) {
        why = "the creator hook pool is full";
        return -1;
    }
    SlotState& s = g_slots[g_used];
    const auto r = hooks().install("gridnode", slot, 0, reinterpret_cast<uint64_t>(g_detours[g_used]), &s.original, &why);
    if (r != hook::Result::Ok) return -1;
    s.slot = slot;
    return int(g_used++);
}

// Every creator that can make `t` or one of its subclasses.
void creatorsFor(const reflect::Type* base, std::vector<uint64_t>& out) {
    for (const reflect::Type& t : registry().data().types)
        if (!t.creators.empty() && registry().isKindOf(&t, base))
            for (const reflect::Creator& c : t.creators) out.push_back(c.creator);
}

} // namespace

int onCreated(const std::string& owner, const std::string& className, gn_created_fn fn, void* user) {
    if (!fn) return GN_ERR_ARGUMENT;
    const reflect::Type* type = registry().find(className);
    if (!type || type->category != reflect::Category::Class) return GN_ERR_NOT_FOUND;
    std::vector<uint64_t> creators;
    creatorsFor(type, creators);
    if (creators.empty()) {
        GN_LOG("%s: on_created(%s): the engine has no creator for this class or its subclasses", owner.c_str(),
               className.c_str());
        return GN_ERR_NOT_FOUND;
    }
    std::unique_lock<std::shared_mutex> lock(g_lock);
    std::vector<int> indexes;
    for (uint64_t creator : creators) {
        uint64_t vt = 0;
        if (!mem::read(creator, vt) || !mem::inImage(vt)) continue;
        std::string why;
        const int i = slotIndex(vt + kCreatorFactorySlot, why);
        if (i < 0) {
            GN_LOG("%s: on_created(%s): creator 0x%llx: %s", owner.c_str(), className.c_str(),
                   static_cast<unsigned long long>(mem::va(creator)), why.c_str());
            continue;
        }
        if (std::find(indexes.begin(), indexes.end(), i) == indexes.end()) indexes.push_back(i);
    }
    if (indexes.empty()) return GN_ERR_UNAVAILABLE;
    for (int i : indexes) g_slots[size_t(i)].listeners.push_back({owner, type, fn, user});
    GN_LOG("%s: on_created(%s): %llu creator slot(s)", owner.c_str(), className.c_str(),
           static_cast<unsigned long long>(indexes.size()));
    return GN_OK;
}

} // namespace gn::host
