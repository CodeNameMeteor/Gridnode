/// The nearest hit between `from` and `to` (radius > 0: a sphere sweep). Server thread only.
pub fn raycast(from: [f32; 3], to: [f32; 3], radius: f32) -> Option<RayHit> {
    let mut h = RayHit {
        position: [0.0; 3],
        normal: [0.0; 3],
        distance: 0.0,
        fraction: 0.0,
    };
    (unsafe { (api().raycast.unwrap())(from.as_ptr(), to.as_ptr(), radius, &mut h) } == 0)
        .then_some(h)
}
/// What a thin ray hit: the hit, the body, the part within it and the server entity that owns
/// it (null for level geometry). Server thread only; per click rather than per tick.
pub fn raycast_object(from: [f32; 3], to: [f32; 3]) -> Option<ObjectHit> {
    let mut h: ObjectHit = unsafe { core::mem::zeroed() };
    h.size = core::mem::size_of::<ObjectHit>() as u32;
    (unsafe { (api().raycast_object.unwrap())(from.as_ptr(), to.as_ptr(), &mut h) } == 0)
        .then_some(h)
}
/// Like `raycast_object`, but the ray passes through the bodies in `ignore` (up to 12 ids; API 33).
pub fn raycast_filtered(from: [f32; 3], to: [f32; 3], ignore: &[u32]) -> Option<ObjectHit> {
    let mut h: ObjectHit = unsafe { core::mem::zeroed() };
    h.size = core::mem::size_of::<ObjectHit>() as u32;
    (unsafe {
        (api().raycast_filtered.unwrap())(
            from.as_ptr(),
            to.as_ptr(),
            ignore.as_ptr(),
            ignore.len() as u32,
            &mut h,
        )
    } == 0)
        .then_some(h)
}
/// A physics entity's collision body ids (empty if it is not one). Any thread.
pub fn entity_bodies(entity: *mut c_void) -> Vec<u32> {
    let mut ids = [0u32; 64];
    let n = unsafe { (api().entity_bodies.unwrap())(entity, ids.as_mut_ptr(), 64) };
    if n > 0 {
        ids[..(n as usize).min(64)].to_vec()
    } else {
        Vec::new()
    }
}
