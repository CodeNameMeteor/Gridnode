/// An event's id from its name, as the engine hashes it (djb2-xor).
pub const fn event_hash(name: &str) -> u32 {
    let b = name.as_bytes();
    let (mut h, mut i) = (5381u32, 0);
    while i < b.len() {
        h = h.wrapping_mul(33) ^ b[i] as u32;
        i += 1;
    }
    h
}
