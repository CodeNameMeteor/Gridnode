/// What [`on_message`] passes along with the message.
pub struct MessageInfo {
    pub type_name: String,
    pub category: String,
    pub type_id: u32,
    pub category_id: u32,
    /// 0 core, 1 client, 2 server.
    pub manager: i32,
}
unsafe extern "C" fn message_tramp<F: FnMut(*const c_void, &MessageInfo)>(
    m: *const c_void,
    i: *const sys::gn_message_info,
    user: *mut c_void,
) {
    let i = &*i;
    let info = MessageInfo {
        type_name: string(i.type_name),
        category: string(i.category),
        type_id: i.type_id,
        category_id: i.category_id,
        manager: i.manager,
    };
    guard("a message callback", (), || (*(user as *mut F))(m, &info))
}
/// `f(message, info)` for a message type (`"ClientPlayerLocalSetMessage"`) or a category
/// (`"ServerPlayer"`), on the thread that sent it. The message only lives during the call.
pub fn on_message<F: FnMut(*const c_void, &MessageInfo) + Send + 'static>(
    type_or_category: &str,
    f: F,
) -> bool {
    let n = cstr(type_or_category);
    unsafe {
        (api().on_message.unwrap())(name(), n.as_ptr(), Some(message_tramp::<F>), keep(f)) == 0
    }
}
